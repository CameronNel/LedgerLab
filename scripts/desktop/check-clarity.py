    day.locator('[data-day-action=discard]').first.click()
    # Mail folders distinguish correspondence from real incoming unread work.
    page.evaluate('ledgerlabPreview.desktop.openMail()');mail=page.locator('[data-window=mail]')
    unread_before=mail.locator('.pc-mail-toolbar small').inner_text()
