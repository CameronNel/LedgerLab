    ck('commas must group' in day.locator('[role=alert]').inner_text(),'Ambiguous decimal comma is rejected visibly')
    ck(amount.input_value()=='1,2','Invalid amount remains visible for correction')
    ck(page.evaluate('!ledgerlabPreview.model().state.workday.submissions["2025-07-welcome"]'),'Rejected amount never saves a response')
    amount.fill('1,234.56');day.locator('[data-day-action=save]').click();idle(page)
    ck('Response draft saved' in day.inner_text(),'Valid grouped amount saves normally')
    ck(123456 in page.evaluate('Object.values(ledgerlabPreview.model().state.workday.submissions["2025-07-welcome"].figures)'),'Valid amount saved as exact integer cents')
    # Changing unrelated mail state must preserve a response cursor and current draft.
    note.fill('A retained response draft while another piece of saved workspace data changes.');note.focus();note.evaluate('(el)=>el.setSelectionRange(12,20)')
    page.evaluate('ledgerlabPreview.session.save({type:"markDesktopMailRead",mailId:"MAIL-WELCOME",read:true})');idle(page)
    ck(note.input_value().startswith('A retained response'),'Unrelated save does not overwrite unsaved response')
    ck(note.evaluate('(el)=>el===document.activeElement&&el.selectionStart===12&&el.selectionEnd===20'),'Unrelated save retains response focus and selected text')
