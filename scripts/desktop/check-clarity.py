    ck('memory' in page.locator('.pc-storage-banner').inner_text().lower(),'Warning does not claim durable storage')
    box=day.locator('.day-task').first.bounding_box()
    ck(box['y']+box['height']<850,'Next task is visible without scrolling at 1440 by 900')
    ck(not day.locator('.day-routine').evaluate('(el)=>el.open'),'Routine is collapsed rather than burying work')
    page.screenshot(path=str(OUT/'01-today.png'))
    day.locator('.day-nav [data-day-action=tasks]').click()
    q=day.locator('[name=day-query]');q.press_sequentially('HANDOVER')
    ck(q.input_value()=='HANDOVER','Task search retains every typed character across repaint')
    ck(q.evaluate('(el)=>el===document.activeElement'),'Task search retains keyboard focus')
    day.locator('[name=day-kind]').select_option('processing')
    ck(day.locator('.day-task').count()==3,'Work area and text query combine')
    q.fill(page.evaluate('ledgerlabPreview.model().company.documents.find(d=>d.id==="HANDOVER-ACCRUAL").title'))
    ck(day.locator('.day-task').count()==1,'Displayed source title can be used to find its task')
    day.locator('[data-day-action=reset-filters]').click()
    ck(q.input_value()=='' and day.locator('[name=day-kind]').input_value()=='all','Reset restores filters together')
    result=page.evaluate('ledgerlabPreview.session.save({type:"advanceWorkday",date:"2025-08-01",note:"Release the closing evidence for pagination checks.",acknowledgeOutstanding:true})')
    ck(result['ok'],'Scenario date advances through actual command validation')
    day.locator('.day-nav [data-day-action=tasks]').click();day.locator('[name=day-filter]').select_option('all')
    ck(day.locator('.day-task').count()==20,'Large task queue is paginated to twenty rows')
    day.locator('[data-day-action=next-page]').click()
    ck('21–40' in day.locator('.day-pages').inner_text(),'Next task page has correct record range')
    q.fill('impossible-reference-zz')
    ck(day.locator('.day-task').count()==0 and 'Page 1 / 1' in day.locator('.day-pages').inner_text(),'No-result query resets out-of-range pagination')
    day.locator('[data-day-action=reset-filters]').click();page.screenshot(path=str(OUT/'02-tasks.png'))
    page.evaluate('ledgerlabPreview.desktop.openDaily("2025-07-welcome")')
