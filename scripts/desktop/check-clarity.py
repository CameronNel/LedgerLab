    page.evaluate('ledgerlabPreview.desktop.openMail("MAIL-WELCOME")')
    ck(mail.get_by_label('Mail folder',exact=True).input_value()=='inbox' and mail.get_by_label('Search scenario emails').input_value()=='','Explicit message links clear stale folder and search filters')
    ck(mail.locator('[data-mail="MAIL-WELCOME"]').get_attribute('data-active')=='true','Explicit message link selects the requested mail')
