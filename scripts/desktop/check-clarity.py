    before=page.evaluate('JSON.stringify(ledgerlabPreview.model().state)')
    page.evaluate('ledgerlabPreview.desktop.openApp("ledger-checks")');health=page.locator('[data-window=ledger-checks]')
    ck(health.locator('.pc-health').is_visible(),'Ledger diagnostics are reachable as a working feature')
    ck('not the worked solution' in health.inner_text(),'Diagnostics clearly distinguish actual-ledger checks from answer grading')
    with page.expect_download() as dl:health.locator('[data-health-export]').click()
    text=Path(dl.value.path()).read_text()
    ck('Severity' in text and 'Finding' in text,'Ledger checks export an inspectable CSV')
    ck(page.evaluate('JSON.stringify(ledgerlabPreview.model().state)')==before,'Diagnostics and export do not post or mutate saved state')
    page.screenshot(path=str(OUT/'03-ledger-checks.png'))
    # Backup shortcut works even when a workbook consumes ordinary Ctrl+S.
    page.evaluate('ledgerlabPreview.desktop.newWorkbook()');page.locator('.xl-formula-input').first.wait_for() if page.locator('.xl-formula-input').count() else None
    with page.expect_download() as dl: page.keyboard.press('Control+Shift+s')
    ck('backup' in dl.value.suggested_filename.lower(),'Dedicated shortcut exports a saved-state backup')
    page.locator('[data-action=global-search]').click();search=page.locator('#ledgerlab-global-query');search.fill('ledger')
    ck(search.get_attribute('role')=='combobox','Search exposes combobox semantics')
    search.press('ArrowDown')
    ck(bool(search.get_attribute('aria-activedescendant')),'Search announces the active keyboard result')
    page.keyboard.press('Escape')
    page.set_viewport_size({'width':390,'height':844});page.evaluate('ledgerlabPreview.desktop.openDaily()')
    ck(page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'),'Narrow workspace has no whole-page horizontal overflow')
    button=page.locator('.pc-storage-banner [data-action=backup-now]').bounding_box()
    ck(button['x']>=0 and button['x']+button['width']<=390,'Narrow-screen backup action fits entirely inside viewport')
    page.locator('.day-nav [data-day-action=today]').click()
    page.locator('.pc-toast').evaluate('(el)=>el.hidden=true')
    page.screenshot(path=str(OUT/'04-mobile.png'))
    ck(errors==[],'No uncaught errors in clarity/safety browser journey')
